package co.edu.uniquindio.preparcial2.ejercicio43;

public class Calculadora {
    public int sumar(int a, int b){
        int resultado=a+b;
        return resultado;
    }
    public int sumar(int a, int b, int c){
        int resultado=a+b+c;
        return resultado;
    }
    public double sumar(double a, double b){
        double resultado=a+b;
        return resultado;
    }
}
